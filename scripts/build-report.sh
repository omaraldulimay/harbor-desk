#!/usr/bin/env bash
# Assembles docs/proof/report.md from the fragments the proof tests write to target/proof.
set -euo pipefail
cd "$(dirname "$0")/.."
out=docs/proof/report.md
{
  echo "# Proof report"
  echo
  echo "Generated by \`make proof\` on $(date +%Y-%m-%d). Numbers come from the proof tests in \`src/test/java/dev/harbordesk/proof\`, run on a laptop against a local Postgres 16."
  echo
  for f in isolation silo noisy-neighbor; do cat "target/proof/$f.md"; echo; done
} > "$out"
echo "wrote $out"
